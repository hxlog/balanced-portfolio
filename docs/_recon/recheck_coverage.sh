sleep 65
cd /opt/balanced-portfolio
echo "--- DB 覆盖 ---"
su - postgres -c "psql -d postgres -tAc \"select count(distinct q.symbol) from bp_index_quote_daily q join bp_index_master m on m.index_code = q.symbol\""
